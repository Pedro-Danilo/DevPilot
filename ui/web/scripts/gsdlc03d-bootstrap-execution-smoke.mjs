import fs from 'node:fs';
const read=(p)=>fs.readFileSync(new URL(`../${p}`,import.meta.url),'utf8');
const view=read('src/pages/ProjectEntryDryRunView.ts');
const client=read('src/api/client.ts');
const approvalView=read('src/pages/ApprovalCenterView.ts');
const styles=read('src/styles.css');
const pkg=JSON.parse(read('package.json'));
const failures=[]; const check=(ok,id)=>{if(!ok)failures.push(id)};
for(const marker of ['GSDLC-03-D','Solicitar approval','Verificar approval','Ejecutar plan aprobado','Abrir Approval Center','defer-network'])check(view.includes(marker),`view:${marker}`);
check(client.includes('/project-entry/execution-approval-request'),'client:approval');
check(client.includes('/project-entry/execute'),'client:execute');
check(client.includes('PROJECT_ENTRY_EXECUTION_TIMEOUT_MS = 240000'),'client:execution-timeout-budget');
check(client.includes('timeoutMs: PROJECT_ENTRY_EXECUTION_TIMEOUT_MS'),'client:execution-timeout-policy');
check(client.includes('execution_unknown')&&client.includes('reconcile_before_retry'),'client:execution-timeout-unknown-state');
check(view.includes('projectEntryRevalidate')&&view.includes('projectEntryRequestExecutionApproval')&&view.includes('showApproval')&&view.includes('projectEntryExecute'),'sequence');
check(view.includes('UNKNOWN · reconciliar antes de reintentar')&&view.includes('error.status===408'),'view:timeout-fail-safe');
check(approvalView.includes("viewer-grid approval-center-grid"),'approval:dedicated-grid');
check(styles.includes('.approval-center-grid > * { min-width: 0; }')&&styles.includes('@media (max-width: 1180px) { .approval-center-grid { grid-template-columns: 1fr; } }'),'approval:responsive-no-overlap');
check(view.includes('textContent')&&!view.includes('innerHTML'),'xss');
check(pkg.devpilot.gsdlc03dApprovalBoundExecution===true,'package:execution');
check(pkg.devpilot.gsdlc03dNetworkExecutionEnabled===false,'package:network');
check(pkg.devpilot.gsdlc03dRemoteGitExecutionEnabled===false,'package:remote-git');
console.log(JSON.stringify({schema_id:'devpilot.gsdlc03d.ui_smoke.v1',status:failures.length?'BLOCK':'PASS',failures},null,2));
process.exit(failures.length?2:0);
